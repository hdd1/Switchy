import AppKit

/// Следит за системным буфером обмена (macOS не присылает уведомлений — опрашиваем changeCount).
@MainActor
final class ClipboardMonitor {
    /// Метки содержимого, которое нельзя сохранять (nspasteboard.org + служебная метка Switchy).
    private static let skippedTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        ClipboardIO.internalType,
    ]

    var onText: ((String, String?) -> Void)?

    private var timer: Timer?
    private var lastChangeCount = NSPasteboard.general.changeCount

    func start() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: Self.skippedTypes),
              let text = pasteboard.string(forType: .string) else { return }
        onText?(text, NSWorkspace.shared.frontmostApplication?.bundleIdentifier)
    }
}
